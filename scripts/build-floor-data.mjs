import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const dataDir = resolve(root, 'src/scene/factory3d');
const blueprint = JSON.parse(readFileSync(resolve(dataDir, 'floor-blueprint.json'), 'utf8'));
const savedPalette = JSON.parse(readFileSync(resolve(dataDir, 'floor-palette.json'), 'utf8'));

function position(payload, key) {
  const body = new RegExp(`${key}:\\{([^}]+)\\}`).exec(payload)?.[1];
  if (!body) throw new Error(`floor-blueprint.json 缺少 ${key}`);
  return ['X', 'Y', 'Z'].map(axis => {
    const value = new RegExp(`${axis}:(-?\\d+)`).exec(body)?.[1];
    if (value === undefined) throw new Error(`floor-blueprint.json 缺少 ${key}.${axis}`);
    return Number(value);
  });
}

const payload = blueprint.statePosArrayList;
if (typeof payload !== 'string') throw new Error('floor-blueprint.json 缺少 statePosArrayList');
const start = position(payload, 'startpos');
const dimensions = position(payload, 'endpos').map((end, index) => end - start[index] + 1);
const [size, layers, depth] = dimensions;
if (size !== depth || dimensions.some(value => value <= 0)) {
  throw new Error(`地板蓝图应为方形的 X/Z 范围，实际为 ${dimensions.join('x')}`);
}

const paletteText = /blockstatemap:\[([\s\S]*?)\],endpos:/.exec(payload)?.[1];
const palette = [...(paletteText || '').matchAll(/Name:"minecraft:([^"]+)"/g)].map(match => match[1]);
const stateText = /statelist:\[I;([^\]]*)\]/.exec(payload)?.[1];
const states = stateText?.split(',').map(Number);
if (!palette.length || palette.length > 256 || states?.length !== size * layers * depth) {
  throw new Error('地板蓝图的调色板或格子数量无效');
}
if (states.some(value => !Number.isInteger(value) || value < 0 || value >= palette.length)) {
  throw new Error('地板蓝图的调色板索引无效');
}
if (savedPalette.size !== size || savedPalette.layers !== layers || savedPalette.palette.join('|') !== palette.join('|')) {
  throw new Error('floor-palette.json 与 floor-blueprint.json 不一致');
}

const cells = new Uint8Array(states.length);
for (let z = 0; z < depth; z++) {
  for (let y = 0; y < layers; y++) {
    for (let x = 0; x < size; x++) {
      // Building Gadgets 按 X、Y、Z 排列；运行时按 X、Z、Y 分层。
      cells[x + z * size + y * size * depth] = states[x + y * size + z * size * layers];
    }
  }
}

const runs = [];
for (let index = 0; index < cells.length;) {
  const value = cells[index];
  let repeat = 1;
  while (index + repeat < cells.length && cells[index + repeat] === value && repeat < 255) repeat++;
  runs.push(value.toString(16).padStart(2, '0'), repeat.toString(16).padStart(2, '0'));
  index += repeat;
}

const air = palette.indexOf('air');
if (air < 0) throw new Error('地板蓝图调色板缺少 air');
const output = `// AUTO-GENERATED by scripts/build-floor-data.mjs -- do not edit.
export const FLOOR_SIZE = ${size};
export const FLOOR_TILE = ${size};
export const FLOOR_LAYERS = ${layers};
export const FLOOR_AIR = ${air};
export const FLOOR_PALETTE = ${JSON.stringify(palette)};
export const FLOOR_RLE_HEX = ${JSON.stringify(runs.join(''))};
`;
writeFileSync(resolve(dataDir, 'floor-data.js'), output, 'utf8');
console.log(`floor-data.js: ${size}x${size}x${layers}, ${cells.length} cells, ${runs.length / 2} runs`);
