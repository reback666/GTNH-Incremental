// Generates src/floor-data.js from assets/floor.bin so the binary can be
// bundled by esbuild without a custom loader.
//
// The blueprint grid is a thin decorative mosaic, so layer bytes are stored
// run-length encoded. Each layer is appended to one byte stream as
// (value, repeat) pairs, so the whole 3-layer grid costs a hex string instead of
// ~450 KB of base64.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { writeFloorData } from "./decode-floor.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
writeFloorData();
const bin = readFileSync(join(root, "assets", "floor.bin"));
const size = bin.readUInt32LE(0);
const palLen = bin.readUInt32LE(4);
const layers = bin.readUInt32LE(8);
const cells = bin.subarray(12, 12 + size * size * layers);
const palette = bin.subarray(12 + size * size * layers).toString("utf8").split("|");

if (palette.length !== palLen) {
  throw new Error(`palette length mismatch: header=${palLen} actual=${palette.length}`);
}
if (cells.length !== size * size * layers) {
  throw new Error(`cell count mismatch: expected ${size * size * layers}, got ${cells.length}`);
}

/** Run-length encode the whole grid into (value, run<=255) pairs. */
function rle(bytes) {
  const pairs = [];
  let i = 0;
  while (i < bytes.length) {
    const v = bytes[i];
    let n = 1;
    while (i + n < bytes.length && bytes[i + n] === v && n < 255) n++;
    pairs.push(v, n);
    i += n;
  }
  return Uint8Array.from(pairs);
}
const packed = rle(cells);

const out = `// AUTO-GENERATED by tools/gen-floor-data.mjs -- do not edit.
export const FLOOR_SIZE = ${size};
export const FLOOR_TILE = 160;
export const FLOOR_LAYERS = ${layers};
export const FLOOR_AIR = 3;
export const FLOOR_PALETTE = ${JSON.stringify(palette)};
// Run-length pairs (value, repeat<=255) covering every layer front to back.
export const FLOOR_RLE_HEX = ${JSON.stringify(Buffer.from(packed).toString("hex"))};
`;
mkdirSync(join(root, "src"), { recursive: true });
writeFileSync(join(root, "src", "floor-data.js"), out);

const raw = cells.length;
console.log(
  `floor-data.js: ${size}x${size}x${layers} (${raw} cells) -> rle ${packed.length} bytes, ` +
    `${palette.length} palette entries, ${(out.length / 1024).toFixed(0)} KB source`
);
